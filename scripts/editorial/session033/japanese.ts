let oldIds = 0, currentInternalLinks = 0, details = 0;
function verify(entry: Entry, actual: string, allNew: Map<string, string>) {
  assert.deepEqual(matter(actual).data, matter(entry.before).data, "changed frontmatter: " + entry.slug);
  const old = load(renderMarkdown(matter(entry.before).content, entry.slug).html);
  const now = load(renderMarkdown(matter(actual).content, entry.slug).html);
  const ids = now("[id]").map((_, e) => now(e).attr("id")!).get();
  assert.equal(ids.length, new Set(ids).size, "duplicate ID: " + entry.slug);
  for (const id of old("[id]").map((_, e) => old(e).attr("id")!).get()) { assert(ids.includes(id), "lost ID: " + entry.slug + "#" + id); oldIds++; }
  const links = now("a[href]").map((_, e) => now(e).attr("href")!).get();
  for (const href of old("a[href]").map((_, e) => old(e).attr("href")!).get().filter(h => h.startsWith("/doc/") || h.startsWith("#"))) assert(links.includes(href), "lost link: " + entry.slug + " " + href);
  assert.equal(now("details[open]").length, 0);
  assert.equal((actual.match(/<details(?:\s[^>]*)?>/g) || []).length, (actual.match(/<\/details>/g) || []).length, "unbalanced details");
  assert(now("details").length >= 2);
  details += now("details").length;
  for (const href of links) {
    assert(!/\.md(?:[?#]|$)/.test(href), "unrewritten link");
    if (!href.startsWith("/doc/") && !href.startsWith("#")) continue;
    const [target, fragment] = href.startsWith("#") ? [entry.slug, href.slice(1)] : href.slice(5).split("#");
    const decoded = decodeURIComponent(target).split("?")[0];
    const file = path.join("knowledge", decoded + ".md");
    assert(fs.existsSync(file), "missing target: " + href);
    currentInternalLinks++;
    if (fragment) {
      const targetRaw = allNew.get(decoded) ?? fs.readFileSync(file, "utf8");
      const rendered = load(renderMarkdown(matter(targetRaw).content, decoded).html);
      assert(rendered("[id]").map((_, e) => rendered(e).attr("id")!).get().includes(decodeURIComponent(fragment)), "missing fragment: " + href);
    }
  }
}
