function inspect(change: Change) {
  const { original, corrected, raw, slug } = change;
  const parsed = matter(raw);
  for (const [name, value] of Object.entries(matter(original).data)) assert.deepEqual(parsed.data[name], value, `Frontmatter changed: ${slug}:${name}`);
  const oldIds = idsOf(original, slug), ids = idsOf(raw, slug), set = new Set(ids);
  assert.equal(ids.length, set.size, `Duplicate IDs: ${slug}`);
  for (const id of oldIds) assert(set.has(id), `Lost old ID: ${slug}#${id}`);
  const oldLinks = internalOf(original, slug), links = internalOf(raw, slug), currentLinks = new Set(links);
  for (const href of oldLinks) assert(currentLinks.has(href), `Lost old internal link: ${slug}:${href}`);
  const $ = load(renderMarkdown(parsed.content, slug).html);
  const old = load(renderMarkdown(corrected, slug).html);
  const currentText = $.text().replace(/\s+/g, " ");
  for (const block of old("pre code").map((_, e) => old(e).text()).get()) assert(currentText.includes(block.replace(/\s+/g, " ").trim()), `Lost corrected old example: ${slug}`);
  assert.equal((raw.match(/<details(?:\s[^>]*)?>/g) || []).length, (raw.match(/<\/details>/g) || []).length, `Details not balanced: ${slug}`);
  assert.equal($("details[open]").length, 0, `Solutions exposed: ${slug}`);
  assert($("details").length >= 2, `Missing disclosure: ${slug}`);
  assert.equal($('a[href$=".md"]').length, 0, `Unconverted .md href: ${slug}`);
  for (const href of links) {
    const [url, fragment] = href.split("#");
    const target = url ? decodeURIComponent(url.slice(5).split("?")[0]) : slug;
    const file = path.join("knowledge", target + ".md");
    assert(fs.existsSync(file), `Broken internal target: ${slug}:${href}`);
    if (fragment) {
      const targetText = target === slug ? raw : fs.readFileSync(file, "utf8");
      assert(idsOf(targetText, target).includes(decodeURIComponent(fragment)), `Broken fragment: ${slug}:${href}`);
    }
  }
  return { oldIds: oldIds.length, oldLinks: oldLinks.length, links: links.length, details: $("details").length };
}
