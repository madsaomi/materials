const ids = (text: string, slug: string) => {
  const $ = load(renderMarkdown(matter(text).content, slug).html);
  return $("[id]").map((_, e) => $(e).attr("id")!).get();
};
const links = (text: string, slug: string) => {
  const $ = load(renderMarkdown(matter(text).content, slug).html);
  return $("a[href]").map((_, e) => $(e).attr("href")!).get()
    .filter(h => h.startsWith("/doc/") || h.startsWith("#")).sort();
};
const escape = (s: string) => s.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
const plans: { slug: string; before: string; after: string; oldIds: number; aliases: number; corrections: number }[] = [];
for (const mirror of ["", "knowledge/"]) for (let i = 0; i < koreanLessons.length; i++) {
  const unit = i + 1, lesson = koreanLessons[i], level = unit < 6 ? "a1" : unit < 11 ? "a2" : "b1";
  for (const kind of ["core", "usage"] as const) {
    const slug = mirror + "languages/korean/" + level + "/unit-" + String(unit).padStart(2, "0") + "/grammar/" + kind;
    const before = fs.readFileSync(path.join(backup, slug + ".md"), "utf8");
    let retained = before.replaceAll("\r\n", "\n"), applied = 0;
    for (const [old, replacement] of corrections[unit + "/" + kind] || []) {
      if (retained.includes(old)) { retained = retained.replaceAll(old, replacement); applied++; }
    }
    const title = /^# .+\n/m.exec(retained);
    assert(title && title.index !== undefined, "Missing title: " + slug);
    const prefix = retained.slice(0, title.index + title[0].length);
    let bank = retained.slice(prefix.length).trim();
    if (kind === "usage") for (const line of generic) bank = bank.replaceAll(line, "");
    const citations = "### Источники для уточнённых правил\n\n" + lesson.sources.map(([label, url, claim]) => "[" + label + "](" + url + "). " + claim).join("\n\n") + "\n\nПримеры и задания учебного ядра составлены для этой библиотеки.";
    let content: string;
    if (kind === "core") {
      content = "## Учебная основа: " + lesson.topic + "\n\n" + lesson.core + "\n\n" + citations;
    } else {
      content = "## Выбор формы в ситуации: " + lesson.topic + "\n\n" + lesson.choice + "\n\n" +
        lesson.checks.map(([task, solution], j) =>
          "### Проверка " + (j + 1) + ": выберите смысл и форму\n\n" + task + "\n\n<details>\n<summary>Решение и объяснение</summary>\n\n" + solution + "\n\n</details>"
        ).join("\n\n") +
        "\n\n### Самостоятельная мини-ситуация\n\n" +
        "Составьте ещё одну реплику для одной из ситуаций выше. Измените цель говорящего так, чтобы потребовалась другая изученная форма, и объясните изменение смысла. Сверяйте образование форм с [учебной основой](core.md).\n\n" + citations;
    }
    let after = prefix + "\n" + content + "\n\n";
    if (kind === "core") after += "## Расширенный справочник урока\n\n> Ниже сохранён прежний банк таблиц и примеров, темы которого шире нового учебного ядра. Конкретные исправления перечислены в отчёте Session036; полной повторной проверки всего большого банка не заявляется.\n\n" + bank + "\n";
    else after += "<details>\n<summary>Прежний разбор и дополнительные пояснения этой версии</summary>\n\n> Здесь сохранены исходные примеры и отдельные дополнения хранилища. Общие задания заменены предметными выше; конкретные исправления не означают полной проверки старого банка.\n\n" + bank + "\n\n</details>\n";
    const beforeIds = ids(before, slug), current = new Set(ids(after, slug));
    const missing = beforeIds.filter(id => !current.has(id));
    if (missing.length) after += "\n" + missing.map(id => '<span id="' + escape(id) + '" aria-hidden="true"></span>').join("\n") + "\n";
    const finalIds = ids(after, slug);
    assert.equal(finalIds.length, new Set(finalIds).size, "Duplicate IDs: " + slug);
    for (const id of beforeIds) assert(finalIds.includes(id), "Lost ID: " + slug + "#" + id);
    const afterLinks = links(after, slug);
    for (const href of links(before, slug)) assert(afterLinks.includes(href), "Lost link: " + slug + " -> " + href);
    assert.equal((after.match(/<details>/g) || []).length, (after.match(/<\/details>/g) || []).length, "Unbalanced answers: " + slug);
    assert(!/<details\s+open/.test(after));
    assert.deepEqual(matter(before).data, matter(after).data, "Metadata changed: " + slug);
    plans.push({slug, before, after, oldIds: beforeIds.length, aliases: missing.length, corrections: applied});
  }
}
