    assert(!/^[^:]*\.md(?:[?#]|$)/.test(href), `Raw Markdown URL: ${p.slug}`);
    const local = /^\/doc\/([^?#]+)(?:\?[^#]*)?(?:#(.*))?$/.exec(href);
    if (!local) return;
    const slug = decodeURIComponent(local[1]), target = path.join(root, slug + ".md");
    assert(fs.existsSync(target), `Missing target: ${p.slug} -> ${slug}`);
