if (applying) fs.writeFileSync(manifestFile, JSON.stringify({ entries }, null, 2));
else {
  assert(fs.existsSync(manifestFile), "run --apply once before verification");
  const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
  assert.deepEqual(manifest.entries, entries);
  let oldIds = 0;
  let links = 0;
  let readings = 0;
  let practices = 0;
  const failures: string[] = [];
  for (const { slug } of entries) {
    const raw = fs.readFileSync(path.join("knowledge", slug + ".md"), "utf8");
    const original = fs.readFileSync(path.join(backup, slug + ".md"), "utf8");
    assert.deepEqual(matter(raw).data, matter(original).data, "changed frontmatter: " + slug);
    const old = load(renderMarkdown(matter(original).content, slug).html);
    const current = load(renderMarkdown(matter(raw).content, slug).html);
    const ids = current("[id]").map((_, e) => current(e).attr("id")!).get();
    assert.equal(new Set(ids).size, ids.length, "duplicate ID: " + slug);
    for (const id of old("[id]").map((_, e) => old(e).attr("id")!).get()) {
      if (!ids.includes(id)) failures.push(`lost ID ${slug}#${id}`);
      oldIds++;
    }
    assert.equal(current("details[open]").length, 0, slug);
    const countOpen = (raw.match(/<details(?:\s[^>]*)?>/g) || []).length;
    const countClose = (raw.match(/<\/details>/g) || []).length;
    assert.equal(countOpen, countClose, "unbalanced disclosure: " + slug);
    if (slug.endsWith("/reading")) {
      readings++;
      assert(current("details").length >= 3, slug);
      assert(current("blockquote").length >= 1, slug);
    } else if (slug.endsWith("/practice/exercises")) {
      practices++;
      assert(current("details").length >= 2, slug);
      for (const letter of ["А", "Б", "В"]) assert(current.text().includes(`Задача ${letter}:`), slug);
    }
    current("a[href]").each((_, el) => {
      const href = current(el).attr("href")!;
      assert(!/\.md(?:[?#]|$)/.test(href), "raw md href: " + slug);
      if (!href.startsWith("/doc/") && !href.startsWith("#")) return;
      const [target, fragment] = href.startsWith("#") ? [slug, href.slice(1)] : href.slice(5).split("#");
      const targetFile = path.join("knowledge", decodeURIComponent(target).split("?")[0] + ".md");
      assert(fs.existsSync(targetFile), "missing target " + targetFile);
      links++;
      if (fragment) {
        const targetHtml = load(renderMarkdown(matter(fs.readFileSync(targetFile, "utf8")).content, target).html);
        const available = new Set(targetHtml("[id]").map((_, e) => targetHtml(e).attr("id")!).get());
        assert(available.has(decodeURIComponent(fragment)), `missing fragment ${slug} -> ${href}`);
      }
    });
  }
  assert.deepEqual(failures, []);
  const result = { notes: entries.length, readings, practices, retainedOriginalIds: oldIds, checkedInternalLinks: links, failures };
  fs.writeFileSync(path.join(backup, "verification.json"), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
}
